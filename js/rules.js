// ---------------------------------------------------------------------
// Применить ответ к статистике темы.
//   stats     — объект из getTopicStats()
//   isCorrect — true / false
// ---------------------------------------------------------------------
function applyAnswerToTopic(stats, isCorrect) {
  const P = RULES.priority;
  stats.attempts += 1;
  stats.lastSeen = todayStr();

  if (isCorrect) {
    stats.correct += 1;
    stats.streak += 1;
    stats.priority += P.onRight;
    if (stats.streak >= 3) stats.priority += P.onStreak;
  } else {
    stats.streak = 0;
    stats.lastWrong = todayStr();
    stats.priority += P.onWrong;
  }
  stats.priority = clamp(stats.priority, P.min, P.max);
}

// ---------------------------------------------------------------------
// Статус темы: "new" (не решали), "weak", "normal" или "mastered".
// ---------------------------------------------------------------------
function topicStatus(stats) {
  const S = RULES.status;
  if (!stats || stats.attempts === 0) return "new";
  const accuracy = stats.correct / stats.attempts;
  if (stats.priority >= S.weakFrom) return "weak";
  if (stats.attempts >= S.minAttempts && accuracy < S.weakAccuracy) return "weak";
  if (stats.priority <= S.masteredPriority && stats.streak >= S.masteredStreak) return "mastered";
  return "normal";
}

// Ограничить число диапазоном [min, max].
function clamp(x, min, max) {
  return Math.max(min, Math.min(max, x));
}
